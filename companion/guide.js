//
// Spoiler layers, from safe to specific:
//   nudge   always shown for the next step: what to do, no names, no bosses
//   where   map room, shown when the player asks "Where?"
//   title   + hint: the event itself, shown on "Show me" or once it's done
//   rewards shown only once the step is done
//
// When a step counts as done (exactly one of these; logic.js test()):
//   p, at   that world's story-progress byte (state.progress[p]) reached `at`. Thresholds and the
//           events they mark come from the KH1FM Archipelago client (gaithern/KH-1FM-AP-LUA,
//           define_world_progress_location_threshholds; event names from Archipelago's Locations.py),
//           which credits RetroAchievements' code notes. p indexes the bridge's progress bytes in the
//           game's world order (7 unused); 14 is Traverse Town's extra byte.
//   pre     [i, v]: story byte i before the main ones (progress_pre) reached v (read on the Thor)
//   items   all these inventory counts reached (Destiny Islands errands; `extra` is shown only)
//   has     an item, spell, ability or Trinity is in the save (logic.js has())
//   reach   the player walked into this map room while the step was current
//   all / any  lists of the above
//   dive    the player is past this point of the Dive (room order), or out of it
//   end     "dive" / "islands": only once the player has moved on
// from    the same kinds of test, for when the game hands the step out. Until then the Guide shows no
//         next step: between objectives, while scenes play, nothing beats a stale or early one.
// optional  doesn't hold up the steps after it
// Hints are short summaries written for this project.
