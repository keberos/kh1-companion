"""Generate companion/data.js from the vendored public data in tools/sources/.

Archipelago (MIT) names every chest and Ansem Report by its save-flag bit:
  chest   location id = 2650000 + byte_index * 10 + bit   (byte_index and bit are 1-based)
  report  location id = 2657000 + byte_index * 10 + bit
The KH1FM randomizer docs (MIT) add, per chest, the room it sits in and its vanilla contents.

Usage:  python tools/gen_data.py
"""
import csv
import json
import re
from collections import defaultdict
from pathlib import Path

from ap_rules import chest_requirements

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "sources"
ROW = re.compile(r'"([^"]+)":\s*KH1LocationData\("([^"]+)",\s*([0-9_]+),\s*"([^"]+)"')


def strip_world(name, world):
    return name[len(world) + 1:] if name.startswith(world + " ") else name


def level_data():
    paths, names = defaultdict(list), {}
    for r in csv.DictReader((SRC / "rando-sora-levelup-abilities.csv").open(encoding="utf-8-sig")):
        if r["Value"].strip() == "-":
            continue
        code = int(r["Value (HEX)"], 16)
        paths[r["Path"]].append([int(r["Level"]), code])
        names[str(code)] = r["Value"].strip()
    stats = sorted([int(r["Level"]), r["Stat Increase"].strip()]
                   for r in csv.DictReader((SRC / "rando-sora-levelup-stats.csv").open(encoding="utf-8-sig")))
    exp = defaultdict(list)
    for r in csv.DictReader((SRC / "rando-exp-chart.csv").open(encoding="utf-8-sig")):
        if r["Character"] == "Sora":
            exp[r["Path"]].append([int(r["Level"]), int(r["EXP to Add"])])
    for curve, rows in exp.items():
        rows.sort()
        assert [lv for lv, _ in rows] == list(range(2, 101)), curve
        exp[curve] = [n for _, n in rows]
    for rows in paths.values():
        rows.sort()
    return {"paths": paths, "names": names, "stats": stats, "exp": exp}


def main():
    chest_rows = {
        int(r["AP Location ID"]): r
        for r in csv.DictReader((SRC / "rando-chest-items.csv").open(encoding="utf-8-sig"))
    }

    reqs = chest_requirements(SRC / "ap-kh1-Rules.py")
    chests, reports = [], []
    for name, world, loc_id, _type in ROW.findall((SRC / "ap-kh1-Locations.py").read_text(encoding="utf-8")):
        loc_id = int(loc_id.replace("_", ""))
        if 2650000 < loc_id < 2656000:
            byte, bit = divmod(loc_id - 2650000, 10)
            c = {"w": world, "n": strip_world(name, world), "B": byte - 1, "b": bit - 1}
            row = chest_rows.get(loc_id)
            if row:
                c["r"] = row["Room"].strip()  # room name, as the randomizer docs spell it
                c["i"] = row["Reward"].strip()  # vanilla contents
            if name in reqs:
                c["q"] = reqs[name]  # what it takes to reach: any one of these sets
            chests.append(c)
        elif 2657000 < loc_id < 2657100:
            byte, bit = divmod(loc_id - 2657000, 10)
            reports.append({"w": world, "n": strip_world(name, world), "B": byte - 1, "b": bit - 1})

    # Room names by world byte, indexed by room byte, from MultiPresence (list index = room byte).
    worlds_cs = (SRC / "multipresence-kh1-Worlds.cs").read_text(encoding="utf-8-sig")
    world_ids = {}
    for wid, name in re.findall(r'case (\d+):\s*getworld\.Add\("([^"]+)"\)', worlds_cs):
        world_ids.setdefault(name, []).append(int(wid))
    rooms_cs = (SRC / "multipresence-kh1-Rooms.cs").read_text(encoding="utf-8-sig")
    typo_fixes = {"Rabitt": "Rabbit", "Cinderalla": "Cinderella", "Cemetary": "Cemetery"}
    room_names = {}
    for world, body in re.findall(r'case "([^"]+)":(.*?)break;', rooms_cs, re.S):
        rooms = re.findall(r'getroom\.Add\("([^"]*)"\)', body)
        for bad, good in typo_fixes.items():
            rooms = [r.replace(bad, good) for r in rooms]
        for wid in world_ids.get(world, []):
            room_names[wid] = rooms

    chests.sort(key=lambda c: (c["w"], c["n"]))
    reports.sort(key=lambda r: r["n"])
    out = ROOT / "companion" / "data.js"
    out.write_text(
        "// Generated by tools/gen_data.py from tools/sources/ (Archipelago + KH1FM-RANDOMIZER, both MIT). Do not edit.\n"
        "// Chests: B = 0-based byte in the flag array, b = 0-based bit (LSB first), r = room, i = vanilla contents,\n"
        "// q = what reaching it takes (Archipelago Beginner logic): any one list; \"Item:n\" = n of it.\n"
        f"window.KH1_CHESTS = {json.dumps(chests, ensure_ascii=False)};\n"
        f"window.KH1_REPORTS = {json.dumps(reports, ensure_ascii=False)};\n"
        "// Room names by world byte, indexed by room byte (Dekirai/MultiPresence, MIT).\n"
        f"window.KH1_ROOM_NAMES = {json.dumps(room_names, ensure_ascii=False, sort_keys=True)};\n"
        "// Sora's level-ups (KH1FM-RANDOMIZER battle-table docs, MIT). paths: [level, code] per dream path,\n"
        "// code >= 0x80 is an ability (id = code & 0x7F), lower codes are bonuses; names: code -> name;\n"
        "// stats: [level, stat]; exp: EXP needed for each level from 2 to 100, per growth curve.\n"
        f"window.KH1_LEVELS = {json.dumps(level_data(), ensure_ascii=False, sort_keys=True)};\n",
        encoding="utf-8",
    )
    print(f"{len(chests)} chests ({sum('r' in c for c in chests)} with rooms), {len(reports)} reports -> {out}")


if __name__ == "__main__":
    main()
